#define	CHARTYPE	unsigned char
#endif
#define	MAXPAT	256

#ifndef	TABTYPE
#define	TABTYPE	long
#endif
typedef TABTYPE Tab;

#include <string.h>
#include <stdlib.h>

static struct
{
	int patlen;
	CHARTYPE pat[MAXPAT];
	Tab delta[256];
	int lastchar;
} pat;

void
prep1(CHARTYPE *base, register int m)
{
	register CHARTYPE *pe, *p;
	register int j;
	register Tab *d;

	pat.patlen = m;
	if(m > MAXPAT)
		abort();
	memcpy(pat.pat, base, m);
	d = pat.delta;
	for(j = 0; j < 256; j++)
		d[j] = pat.patlen;
	for(p = pat.pat, pe = p+m-1; p < pe; p++)
		d[*p] = pe-p;
	pat.lastchar = *p;
}

int
exec1(CHARTYPE *base, int n)
{
	int nmatch = 0;
	register CHARTYPE *e, *s;
	register Tab *d0 = pat.delta;
	int lastdelta;
	register CHARTYPE *p, *q;
	register CHARTYPE *ep;
	register int n1 = pat.patlen-1;

	lastdelta = n+pat.patlen;
	d0[pat.lastchar] = lastdelta;	/* guaranteed to break s < e loop */
	s = base+pat.patlen-1;
	e = base+n;
	ep = pat.pat + pat.patlen-1;
	while(s < e){
#ifdef	STATS
		for(;;){
			stats.jump++;
			if((s += (k = d0[*s])) >= e) break;
			stats.step[k]++;
		}
		if(s < e+pat.patlen)
			stats.step[k]++;
#else
		while((s += d0[*s]) < e)
			;
#endif
		if(s < e+pat.patlen)	/* no match */
			break;
		s -= lastdelta;
#ifdef	STATS
		stats.slow++;
#endif
		for(p = pat.pat, q = s-n1; p < ep; ){
#ifdef	STATS
			stats.cmp++;
#endif
			if(*q++ != *p++)
				goto mismatch;
		}
		nmatch++;
	mismatch:
		s++;
#ifdef	STATS
		stats.step[1]++;
#endif
	}
	return(nmatch);
}

